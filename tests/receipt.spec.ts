import { expect } from "chai";
import { PublicKey } from "@solana/web3.js";
import BN from "bn.js";
import fs from "fs";
import path from "path";
import {
  encodeReceipt,
  decodeReceipt,
  hashReceipt,
  ReceiptData,
  RECEIPT_CANONICAL_LEN,
  RECEIPT_VERSION,
} from "../packages/anchor-client/src/receipt";

describe("Receipt Canonical Encoding & Vector Tests", () => {
  const vectorsPath = path.join(__dirname, "receipt_vectors.json");
  const vectors = JSON.parse(fs.readFileSync(vectorsPath, "utf8"));

  it("matches test vectors generated by Rust specification", () => {
    for (const vector of vectors) {
      const receipt: ReceiptData = {
        version: vector.version,
        provider: new PublicKey(Buffer.from(vector.provider, "hex")),
        buyer: new PublicKey(Buffer.from(vector.buyer, "hex")),
        requestHash: Buffer.from(vector.requestHash, "hex"),
        responseHash: Buffer.from(vector.responseHash, "hex"),
        paymentReference: Buffer.from(vector.paymentReference, "hex"),
        price: new BN(vector.price),
        timestamp: new BN(vector.timestamp),
        nonce: new BN(vector.nonce),
      };

      const encoded = encodeReceipt(receipt);
      expect(encoded.length).to.equal(RECEIPT_CANONICAL_LEN);
      expect(encoded.length).to.equal(vector.byteLength);
      expect(encoded.toString("hex")).to.equal(vector.canonicalBytesHex);

      const hash = hashReceipt(encoded);
      expect(hash.toString("hex")).to.equal(vector.receiptHashHex);

      // Roundtrip decode
      const decoded = decodeReceipt(encoded);
      expect(decoded.version).to.equal(RECEIPT_VERSION);
      expect(decoded.provider.toBuffer().toString("hex")).to.equal(vector.provider);
      expect(decoded.buyer.toBuffer().toString("hex")).to.equal(vector.buyer);
      expect(decoded.requestHash.toString("hex")).to.equal(vector.requestHash);
      expect(decoded.responseHash.toString("hex")).to.equal(vector.responseHash);
      expect(decoded.paymentReference.toString("hex")).to.equal(vector.paymentReference);
      expect(decoded.price.toString()).to.equal(vector.price);
      expect(decoded.timestamp.toString()).to.equal(vector.timestamp);
      expect(decoded.nonce.toString()).to.equal(vector.nonce);
    }
  });

  it("rejects corrupted or truncated receipt buffers", () => {
    const invalidShort = Buffer.alloc(100);
    expect(() => decodeReceipt(invalidShort)).to.throw(/Invalid buffer length/);

    const invalidLong = Buffer.alloc(250);
    expect(() => decodeReceipt(invalidLong)).to.throw(/Invalid buffer length/);
  });

  it("validates numerical bounds and two's complement signed timestamp", () => {
    const baseReceipt: ReceiptData = {
      version: 1,
      provider: PublicKey.default,
      buyer: PublicKey.default,
      requestHash: Buffer.alloc(32, 1),
      responseHash: Buffer.alloc(32, 2),
      paymentReference: Buffer.alloc(64, 3),
      price: 1000,
      timestamp: -500, // Negative timestamp
      nonce: 42,
    };

    // Negative timestamp encoded in two's complement roundtrips correctly
    const encoded = encodeReceipt(baseReceipt);
    const decoded = decodeReceipt(encoded);
    expect(decoded.timestamp.toString()).to.equal("-500");

    // Negative price should throw
    expect(() => encodeReceipt({ ...baseReceipt, price: -10 })).to.throw(/unsigned 64-bit/);

    // Negative nonce should throw
    expect(() => encodeReceipt({ ...baseReceipt, nonce: -1 })).to.throw(/unsigned 64-bit/);

    // Unsafe floating point number should throw
    expect(() => encodeReceipt({ ...baseReceipt, price: 12.34 })).to.throw(/safe integer/);
    expect(() => encodeReceipt({ ...baseReceipt, timestamp: NaN })).to.throw(/safe integer/);

    // Out of bounds u64 should throw
    const tooBigU64 = new BN("10000000000000000", 16); // 2^64
    expect(() => encodeReceipt({ ...baseReceipt, price: tooBigU64 })).to.throw(/unsigned 64-bit/);
  });
});

